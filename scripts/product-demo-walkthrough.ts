import { chromium, expect } from '@playwright/test';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { verifyWorkspaceProof } from '../server/workspace-proof.ts';

const args = process.argv.slice(2), baseFlag = args.indexOf('--base'), outFlag = args.indexOf('--out');
if (baseFlag < 0 || outFlag < 0 || !args[baseFlag + 1] || !args[outFlag + 1]) throw new Error('Usage: node --import tsx scripts/product-demo-walkthrough.ts --base http://127.0.0.1:<demo-port> --out <new-directory>');
const base = new URL(args[baseFlag + 1]), output = resolve(args[outFlag + 1]);
if (base.protocol !== 'http:' || base.hostname !== '127.0.0.1' || base.port === '4194') throw new Error('The walkthrough requires an isolated loopback demo, never the existing product server.');
const session = await (await fetch(new URL('/api/session', base))).json();
if (session.localDemo !== true || session.providerMode !== 'synthetic' || session.hosted) throw new Error('Refusing to record a workspace that is not the isolated synthetic demo.');
if (existsSync(output)) throw new Error('Use a new capture directory; walkthrough artifacts are never overwritten.');
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 820 }, recordVideo: { dir: output, size: { width: 1280, height: 820 } }, acceptDownloads: true });
let externalRequests = 0;
await context.route('**/*', route => { const url = new URL(route.request().url()); if (url.origin === base.origin || ['data:', 'blob:'].includes(url.protocol)) return route.continue(); externalRequests++; return route.abort(); });
const page = await context.newPage(); page.setDefaultTimeout(10_000);
const started = Date.now(), stages: { stage: string; elapsedMs: number }[] = [];
let proofSha256 = '';
async function pause(stage: string, milliseconds: number) { stages.push({ stage, elapsedMs: Date.now() - started }); console.log(stage); await page.waitForTimeout(milliseconds); }
try {
  await page.goto(base.href);
  await expect(page.locator('.ask-recovery-note')).toContainText('no additional generation call');
  await expect(page.locator('.automatic-check-heading h3')).toHaveText('Repaired · synthetic check passed');
  await page.screenshot({ path: join(output, 'product-workflow-entry-2026-10-17.png') });
  await pause('Recovered original and checked delivery', 6_000);
  await page.locator('.automatic-check-original summary').click();
  await expect(page.locator('.automatic-check-original')).toContainText('eight cups');
  await pause('Original claim: eight cups; saved source: six', 6_000);
  await page.locator('.automatic-check-assessments summary').click();
  await pause('Inspect the exact scripted flaw and independent recheck', 6_000);
  await page.locator('.ask-sources-details>summary').click();
  await page.locator('.ask-sources-details').scrollIntoViewIfNeeded();
  await pause('Expand the complete source body and literal citation', 5_000);
  await page.screenshot({ path: join(output, 'product-workflow-2026-10-17.png'), fullPage: true });
  await page.locator('.ask-history').scrollIntoViewIfNeeded();
  await page.getByRole('button', { name: /maximum temperature rating of the Aster box/ }).click();
  await expect(page.locator('.automatic-check-heading h3')).toHaveText('Check inconclusive');
  await page.locator('.ask-result').scrollIntoViewIfNeeded();
  await pause('Uncertain check stops safely and preserves the original', 6_000);
  await page.locator('#proof').scrollIntoViewIfNeeded();
  await pause('Paired cohort: one scripted win and one unresolved case', 6_000);
  await page.getByRole('button', { name: 'Quality · time · allowance', exact: true }).click();
  await pause('Separate time, provider calls, operations and allowances', 6_000);
  await page.locator('.ask-policy>summary').click();
  await expect(page.locator('.ask-policy-decision')).toContainText('rejected');
  await page.locator('.ask-policy-decision').scrollIntoViewIfNeeded();
  await pause('A real frozen synthetic evaluation rejects blanket abstention', 7_000);
  await page.locator('#proof').scrollIntoViewIfNeeded();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Export exact paired evidence' }).click();
  await (await downloadPromise).saveAs(join(output, 'synthetic-paired-proof.json'));
  proofSha256 = verifyWorkspaceProof(JSON.parse(readFileSync(join(output, 'synthetic-paired-proof.json'), 'utf8'))).sha256;
  await pause('Export the exact source, version, receipt and outcome evidence', 5_000);
  await page.locator('.historical-replay>summary').click();
  await page.locator('.historical-replay').scrollIntoViewIfNeeded();
  await pause('Separately labeled recorded live replay; no fresh inference', 6_000);
  const remaining = 72_000 - (Date.now() - started); if (remaining > 0) await page.waitForTimeout(remaining);
  const durationMs = Date.now() - started;
  if (durationMs < 60_000 || durationMs > 90_000) throw new Error('Walkthrough duration is outside its 60–90 second scope.');
  await context.close();
  await page.video()!.saveAs(join(output, 'product-workflow-2026-10-17.webm'));
  writeFileSync(join(output, 'capture.json'), JSON.stringify({ provenance: 'actual_browser_synthetic_demo_recording', durationMs, externalRequests, providerCalls: 0, proofSha256, proofVerifiedOffline: true, qualityClaimEligible: false, stages }, null, 2) + '\n', { flag: 'wx' });
  console.log(JSON.stringify({ output, durationMs, externalRequests, providerCalls: 0 }));
} finally { await context.close(); await browser.close(); }
