test('v1 and historical flat request bytes remain frozen while v2 changes only its declared prompt/tool identity', () => {
  const prior = workspaceGenerationParts(fixtureInput), explicit = workspaceGenerationParts({ ...fixtureInput, generationContract: WORKSPACE_GENERATION_CONTRACT });
  // Recorded from the pre-change HEAD implementation, independently imported
  // before adding these tests. This is not a snapshot generated by the candidate.
  assert.equal(textHash(JSON.stringify(prior.body)), 'f9390eeaaa9b3b3595adba9b330cfe408bae72625286aef45aa0f90675e1cec1');
  assert.equal(prior.binding.systemInstructionsSha256, 'bee83f3637714b8c1d3345689d64b89748f2ba14887a6226ee5de33f53eb8d8f');
  assert.equal(textHash(JSON.stringify(flatSourceIdAnswerRequestBody(fixtureInput))), '5142bcde4c5475f63183f5d0a399e54db986b2e1d264106da951102f25b6d4e3');
  assert.deepEqual(explicit, prior);
  const candidate = workspaceGenerationParts({ ...fixtureInput, generationContract: WORKSPACE_SOURCE_CALIBRATION_CONTRACT });
  assert.equal(candidate.binding.systemInstructionsSha256, 'e9faddec60d475fe358b01e6c7464eb2993848e982a764f7c12b122266d148f8');
  assert.equal(workspaceGenerationPromptIdentity(WORKSPACE_SOURCE_CALIBRATION_CONTRACT).systemInstructionsSha256, candidate.binding.systemInstructionsSha256);
  assert.notEqual(candidate.binding.requestSha256, prior.binding.requestSha256);
  for (const key of ['sourceContextSha256', 'optionSetSha256', 'responseSchemaSha256', 'policySha256'] as const) assert.equal(candidate.binding[key], prior.binding[key]);
  const normalize = (body: typeof prior.body) => {
    const copy = structuredClone(body), payload = JSON.parse(copy.messages[1].content);
    delete payload.promptVersion; copy.messages[1].content = JSON.stringify(payload); copy.messages[0].content = '<versioned system>';
    copy.tools[0].function.name = prior.tool; copy.tool_choice.function.name = prior.tool; return copy;
  };
  assert.deepEqual(normalize(candidate.body), normalize(prior.body), 'model, settings, schema, question, source order and policy remain controlled');
  const request = { productId, question: fixtureInput.question, mode: 'live' as const };
  assert.equal(workspaceQuestionRequestHash(request), textHash(JSON.stringify({ ...request, automaticCheck: false })));
  assert.notEqual(workspaceQuestionRequestHash(request, false, WORKSPACE_SOURCE_CALIBRATION_CONTRACT), workspaceQuestionRequestHash(request));
});

test('opt-in v2 survives an actual synthetic workspace receipt/restart and remains separate from default idempotency', async () => {
  const directory = mkdtempSync(join(tmpdir(), 'workspace-calibration-synthetic-')), path = join(directory, 'workspace.sqlite');
  const provider = new SyntheticAnswerProvider(join(directory, 'receipts.sqlite'));
  let workspace = new ProductWorkspace(path, provider, retriever, undefined, { fault(boundary) { if (boundary === 'after_receipt') throw new Error('SYNTHETIC interruption'); } });
  try {
    const product = workspace.createProduct({ title: fixtureInput.product.title, sources: [{ label: 'Manual', text: sourceText }] });
    const input = { productId: product.id, question: fixtureInput.question, mode: 'synthetic' }, options = { generationContract: WORKSPACE_SOURCE_CALIBRATION_CONTRACT, idempotencyKey: 'candidate-request' };
    await assert.rejects(workspace.ask(input, undefined, options), /SYNTHETIC interruption/);
    const before = workspace.proofRuns()[0], receipt = provider.receipt(before.id)!;
    assert.equal(before.generation?.phase, 'dispatching'); assert.equal(receipt.kind, WORKSPACE_SOURCE_CALIBRATION_TOOL);
    assert.equal(JSON.parse(receipt.receipt_json!).promptVersion, WORKSPACE_SOURCE_CALIBRATION_CONTRACT);
    workspace.close(); workspace = new ProductWorkspace(path, provider, retriever);
    const recovered = await workspace.ask(input, undefined, options);
    assert.equal(recovered.status, 'completed'); assert.equal(recovered.id, before.id); assert.equal(recovered.generation?.recovered, true);
    assert.equal(recovered.requestIdentity?.generationContract, WORKSPACE_SOURCE_CALIBRATION_CONTRACT); verifyWorkspaceRunGeneration(recovered);
    assert.equal(provider.receipt(recovered.id)?.id, receipt.id); assert.equal(workspace.reviewSnapshots(recovered.id)[0].promptVersion, WORKSPACE_SOURCE_CALIBRATION_CONTRACT);
    assert.ok(recovered.answer!.answer.startsWith('SYNTHETIC'));
    await assert.rejects(workspace.ask(input, undefined, { idempotencyKey: options.idempotencyKey }), /different question request/);
    const original = await workspace.ask(input, undefined, { idempotencyKey: 'default-request' });
    assert.equal(original.generationProtocol, WORKSPACE_GENERATION_CONTRACT); assert.equal(original.requestIdentity?.generationContract, undefined);
    assert.equal((await workspace.ask(input, undefined, { idempotencyKey: 'default-request', generationContract: WORKSPACE_GENERATION_CONTRACT })).id, original.id);
    await assert.rejects(workspace.ask(input, undefined, { idempotencyKey: 'default-request', generationContract: WORKSPACE_SOURCE_CALIBRATION_CONTRACT }), /different question request/);
    const db = new DatabaseSync(path); try { db.prepare('DELETE FROM workspace_question_requests').run(); } finally { db.close(); }
    assert.equal((await workspace.ask(input, undefined, options)).id, recovered.id);
    await assert.rejects(workspace.ask(input, undefined, { idempotencyKey: options.idempotencyKey }), /saved request identity/);
    const proof = buildWorkspaceProof(workspace.proofRuns(), [], provider.receipt.bind(provider));
    assert.equal(verifyWorkspaceProof(proof).valid, true); assert.equal(proof.qualityClaimEligible, false); assert.equal(proof.accounting.calls, 0);
  } finally { workspace.close(); provider.close(); rmSync(directory, { recursive: true, force: true }); }
});

function transportHarness(output: (payload: ReturnType<typeof workspaceGenerationParts>['payload']) => unknown, fault?: (boundary: WorkspaceFaultBoundary) => void) {
  const directory = mkdtempSync(join(tmpdir(), 'workspace-calibration-transport-')), path = join(directory, 'workspace.sqlite');
  let dispatches = 0, captured: ReturnType<typeof workspaceGenerationParts>['body'] | undefined;
  const provider = new SapiomFeedbackProvider({ enabled: true, apiKey: 'SYNTHETIC scripted transport placeholder', credentialsFile: '', dbPath: join(directory, 'ledger.sqlite'), capUsd: 2, callLimit: 10, fetchImpl: async (_url, init) => {
    dispatches++; captured = JSON.parse(String(init?.body));
    return new Response(JSON.stringify({ model: 'gpt-luna', usage: { prompt_tokens: 17, completion_tokens: 11 }, choices: [{ finish_reason: 'tool_calls', message: { tool_calls: [{ function: { name: captured!.tools[0].function.name, arguments: JSON.stringify(output(JSON.parse(captured!.messages[1].content))) } }] } }] }));
  } });
  let workspace = new ProductWorkspace(path, provider, retriever, undefined, { fault: boundary => fault?.(boundary) });
  const product = workspace.createProduct({ title: fixtureInput.product.title, sources: [{ label: 'Manual', text: sourceText }] });
  const input = { productId: product.id, question: fixtureInput.question, mode: 'live' }, options = { generationContract: WORKSPACE_SOURCE_CALIBRATION_CONTRACT, idempotencyKey: 'one-candidate' };
  return { directory, path, provider, input, options, get workspace() { return workspace; }, get captured() { return captured; }, get dispatches() { return dispatches; },
    reopen() { workspace.close(); workspace = new ProductWorkspace(path, provider, retriever); },
    close() { workspace.close(); provider.close(); rmSync(directory, { recursive: true, force: true }); } };
}

test('v2 exact helper, actual workspace transport and durable replay agree without a second reservation', async () => {
  const h = transportHarness(payload => ({ answer: 'x'.repeat(1500), status: 'answered', citations: [payload.quoteOptions[0].id] }));
  try {
    const run = await h.workspace.ask(h.input, undefined, h.options), parts = workspaceGenerationParts(run.generation!.input);
    assert.equal(run.status, 'completed'); assert.equal(run.answer?.answer.length, 1500); assert.equal(run.answer?.citations[0].quote, sourceText);
    assert.deepEqual(h.captured, parts.body); assert.equal(h.captured!.tools[0].function.name, WORKSPACE_SOURCE_CALIBRATION_TOOL);
    const receipt = h.provider.receipt(run.id)!, document = JSON.parse(receipt.receipt_json!);
    for (const [key, value] of Object.entries(parts.binding)) assert.equal(document[key], value);
    assert.equal((await h.provider.answerWorkspace(run.generation!.input)).attemptId, receipt.id);
    await assert.rejects(h.provider.answerWorkspace({ ...run.generation!.input, generationContract: WORKSPACE_GENERATION_CONTRACT }), /reconciliation/);
    assert.deepEqual(replayWorkspaceGenerationReceipt(run.generation!.input, receipt, 'live').answer, run.answer);
    assert.throws(() => replayWorkspaceGenerationReceipt({ ...run.generation!.input, generationContract: WORKSPACE_GENERATION_CONTRACT }, receipt, 'live'), /reconciliation/);
    h.reopen(); assert.equal((await h.workspace.ask(h.input, undefined, h.options)).id, run.id); assert.equal(h.dispatches, 1);
  } finally { h.close(); }
});

test('v2 retains output limits and strict citation rejection with one recorded attempt and no retry', async () => {
  for (const behavior of ['oversize', 'unknown', 'duplicate', 'object_shape', 'uncited', 'marker'] as const) {
    const h = transportHarness(payload => {
      const result = { answer: 'A synthetic scripted answer.', status: 'answered', citations: [payload.quoteOptions[0].id] };
      if (behavior === 'oversize') result.answer = 'x'.repeat(1501);
      if (behavior === 'unknown') result.citations = ['src_unknown_context'];
      if (behavior === 'duplicate') result.citations.push(result.citations[0]);
      if (behavior === 'object_shape') return { ...result, citations: [{ quoteId: result.citations[0] }] };
      if (behavior === 'uncited') result.citations = [];
      if (behavior === 'marker') result.answer += ' [src_unknown_context]';
      return result;
    });
    try {
      const run = await h.workspace.ask(h.input, undefined, h.options);
      assert.equal(run.status, 'failed', behavior); assert.equal(run.answer, null); assert.equal(h.provider.receipt(run.id)?.error_code, 'output_validation');
      h.reopen(); assert.equal((await h.workspace.ask(h.input, undefined, h.options)).status, 'failed'); assert.equal(h.dispatches, 1);
    } finally { h.close(); }
  }
});

test('unknown/internal contract selection cannot silently fall back or enter public question input', async () => {
  const h = transportHarness(() => { throw new Error('No transport expected.'); });
  try {
    const unknown = 'unrecognized-contract' as typeof WORKSPACE_SOURCE_CALIBRATION_CONTRACT;
    await assert.rejects(h.workspace.ask(h.input, undefined, { generationContract: unknown }), /Unknown workspace generation contract/);
    await assert.rejects(h.provider.answerWorkspace({ ...fixtureInput, generationContract: unknown }), /Unknown workspace generation contract/);
    await assert.rejects(h.workspace.ask({ ...h.input, generationContract: WORKSPACE_SOURCE_CALIBRATION_CONTRACT }), /Unrecognized key/);
    await assert.rejects(h.workspace.ask({ ...h.input, mode: 'preview' }, undefined, h.options), /experimental generation/);
    assert.equal(h.workspace.proofRuns().length, 0); assert.equal(h.provider.receipt(fixtureInput.runId), undefined); assert.equal(h.dispatches, 0);
  } finally { h.close(); }
});

test('a changed persisted v2 contract cannot materialize a completed receipt on recovery', async () => {
  const h = transportHarness(payload => ({ answer: 'A synthetic scripted answer.', status: 'answered', citations: [payload.quoteOptions[0].id] }), boundary => { if (boundary === 'after_receipt') throw new Error('SYNTHETIC interruption'); });
  try {
    await assert.rejects(h.workspace.ask(h.input, undefined, h.options), /SYNTHETIC interruption/);
    const run = h.workspace.proofRuns()[0]; run.generation!.input.generationContract = WORKSPACE_GENERATION_CONTRACT;
    const db = new DatabaseSync(h.path); try { db.prepare('UPDATE workspace_runs SET document=? WHERE id=?').run(JSON.stringify(run), run.id); } finally { db.close(); }
    h.reopen(); const recovered = h.workspace.proofRuns()[0]; assert.equal(recovered.status, 'failed'); assert.equal(recovered.answer, null);
    assert.equal(h.provider.receipt(run.id)?.status, 'completed'); assert.equal(h.dispatches, 1);
  } finally { h.close(); }
});
